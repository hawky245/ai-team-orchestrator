"""Pydantic models for the AI Team MVP."""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Shared / low-level models
# ---------------------------------------------------------------------------


class TaskStatus(str, Enum):
    """Lifecycle status of a single task."""
    PENDING = "pending"
    IN_PROGRESS = "in_progress"
    REQUIRES_USER_INPUT = "requires_user_input"
    COMPLETED = "completed"
    APPROVED = "approved"
    REJECTED = "rejected"
    APPROVED_AFTER_RETRY = "approved_after_retry"


class RunStatus(str, Enum):
    """Lifecycle status of a full orchestration run."""
    PENDING = "pending"
    RUNNING = "running"
    REQUIRES_USER_INPUT = "requires_user_input"
    COMPLETED = "completed"
    FAILED = "failed"


# ---------------------------------------------------------------------------
# Core domain models
# ---------------------------------------------------------------------------


class Task(BaseModel):
    """A single unit of work generated by the Planner and executed by the Worker."""
    task_id: str
    description: str
    dependencies: List[str] = Field(default_factory=list)
    requires_user_input: bool = False
    model_override: Optional[str] = None
    context: Dict[str, Any] = Field(default_factory=dict)
    output: Optional[str] = None
    status: TaskStatus = TaskStatus.PENDING
    attempts: int = 0
    created_at: datetime = Field(default_factory=datetime.utcnow)


class TaskPlan(BaseModel):
    """The structured output produced by the Planner agent."""
    summary: str
    tasks: List[Task]
    execution_order: str = "sequential"  # "sequential" | "parallel" | "dag"


class WorkerResult(BaseModel):
    """Result returned by the Worker after executing a Task."""
    raw_output: str


class ReviewResult(BaseModel):
    """Result returned by the Reviewer after evaluating a Worker output."""
    is_valid: bool
    feedback: str
    issues: List[str] = Field(default_factory=list)
    suggestions: List[str] = Field(default_factory=list)
    retry_allowed: bool = True
    needs_user_input: bool = False
    score: float = 0.0


# ---------------------------------------------------------------------------
# Agent output wrappers
# ---------------------------------------------------------------------------


class PlannerOutput(BaseModel):
    """Wrapper around the raw Planner result with metadata."""
    raw_text: str
    tasks: List[Task] = Field(default_factory=list)
    plan_summary: str = ""
    execution_order: str = "dag"


# ---------------------------------------------------------------------------
# Run state (in‑memory for Milestone 1)
# ---------------------------------------------------------------------------


class RunState(BaseModel):
    """Mutable state maintained by the Orchestrator throughout a run.

    In Milestone 1 this lives in memory.  Future milestones persist it to a DB.
    """
    run_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    status: RunStatus = RunStatus.PENDING
    current_goal: Optional[str] = None
    planner_output: Optional[PlannerOutput] = None
    current_task: Optional[Task] = None
    total_tasks: int = 0
    created_at: datetime = Field(default_factory=datetime.utcnow)
    started_at: Optional[datetime] = None
    finished_at: Optional[datetime] = None
